"""Encode the local speech WAVs as small 12 kHz IMA ADPCM clips for the board."""
from array import array
import json
from pathlib import Path
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]
STEPS = (7,8,9,10,11,12,13,14,16,17,19,21,23,25,28,31,34,37,41,45,50,55,60,66,73,80,88,97,107,118,130,143,157,173,190,209,230,253,279,307,337,371,408,449,494,544,598,658,724,796,876,963,1060,1166,1282,1411,1552,1707,1878,2066,2272,2499,2749,3024,3327,3660,4026,4428,4871,5358,5894,6484,7132,7845,8630,9493,10442,11487,12635,13899,15289,16818,18500,20350,22385,24623,27086,29794,32767)
INDEX = (-1,-1,-1,-1,2,4,6,8)


def encode(samples):
    predictor, index = 0, 0
    result = bytearray()
    pending = None
    for sample in samples:
        step = STEPS[index]
        difference = sample - predictor
        code = 8 if difference < 0 else 0
        difference = abs(difference)
        delta = step >> 3
        for mask, value in ((4, step), (2, step >> 1), (1, step >> 2)):
            if difference >= value:
                code |= mask; difference -= value; delta += value
        predictor = max(-32768, min(32767, predictor + (-delta if code & 8 else delta)))
        index = max(0, min(88, index + INDEX[code & 7]))
        if pending is None: pending = code
        else: result.append(pending | code << 4); pending = None
    if pending is not None: result.append(pending)
    return result


def main():
    root = ROOT / 'assets/device/voice'
    config = json.loads((root / 'phrases.json').read_text())
    output = ['// Generated by tools/export_device_voice.py from offline speech WAVs.', '#pragma once', '#include <stdint.h>', 'struct PetVoiceClip { const uint8_t* data; uint32_t samples; };']
    clips, total = [], 0
    for name in config['phrases']:
        with wave.open(str(root / (name + '.wav')), 'rb') as wav:
            assert (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) == (1, 2, 12000)
            samples = array('h', wav.readframes(wav.getnframes()))
            if sys.byteorder != 'little': samples.byteswap()
        # Trim synthesis silence, normalize and fade edges before compression.
        bounds = [i for i, v in enumerate(samples) if abs(v) > 96]
        samples = samples[max(0, bounds[0]-120):min(len(samples), bounds[-1]+240)]
        peak = max(abs(v) for v in samples) or 1
        for i, value in enumerate(samples):
            fade = min(1, i / 120, (len(samples)-1-i) / 120)
            samples[i] = round(value * 32767 / peak * fade)
        data = encode(samples); total += len(data)
        output.append('static const uint8_t voice_' + name + '[] = {')
        output.extend(','.join(str(b) for b in data[i:i+32]) + ',' for i in range(0,len(data),32))
        output.append('};')
        clips.append('{voice_' + name + ',' + str(len(samples)) + '}')
        print(name, round(len(samples)/12000,2), 'seconds', len(data), 'bytes')
    output.append('static const PetVoiceClip petVoiceClips[] = {' + ','.join(clips) + '};')
    output.append('static constexpr uint32_t PET_VOICE_SAMPLE_RATE = 12000;')
    (ROOT / 'firmware/AgentPets_ES3C35P/device_voice.h').write_text('\n'.join(output)+'\n',encoding='utf-8')
    assert total < 48000, total
    print('Total compressed speech:', total, 'bytes')

if __name__ == '__main__': main()
